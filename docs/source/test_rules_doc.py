"""docs/HOW_TO_PLAY.md must agree with the engine's numbers."""
import pathlib

from hollowmere_sim.config import SimConfig
from hollowmere_sim.houses import HOUSE_PROFILES

TEXT = (pathlib.Path(__file__).resolve().parent.parent / "docs" / "HOW_TO_PLAY.md").read_text(encoding="utf-8")
CFG = SimConfig()


def test_build_and_keep_cost():
    assert dict(CFG.build_cost) == {"G": 1, "T": 1, "S": 1}
    assert "| Build | 1 Grain, 1 Timber, 1 Stone |" in TEXT and "| Keep | 1 Grain, 1 Timber, 1 Stone |" in TEXT


def test_muster_raid_and_recapture_costs():
    default = HOUSE_PROFILES["Wren"]
    assert (default.mus_iron, default.raid_iron) == (2, 1)
    assert HOUSE_PROFILES["Maelor"].mus_iron == 3
    assert "| Muster | 2 Iron, 1 Grain (Maelor 3 Iron) |" in TEXT
    assert "| Raid | 1 Iron |" in TEXT
    assert dict(CFG.recapture_cost) == {"I": 1, "G": 1}
    assert "| Recapture | 1 Iron, 1 Grain |" in TEXT


def test_pass_favor_and_dynasty():
    assert CFG.pass_cost_coin == 1 and "| Pass | 1 Coin if you have it |" in TEXT
    assert CFG.dynasty_cost_reed == 2 and HOUSE_PROFILES["Wren"].dyn_favor == 3 and HOUSE_PROFILES["Verrin"].dyn_favor == 2
    assert "| Dynasty | 3 Favor (Verrin 2) and 2 Reed |" in TEXT
    assert CFG.dynasty_purchase_renown == 2 and CFG.dynasty_flood_renown == 1


def test_scoring_numbers():
    assert CFG.mid_flood_points == (3, 0) and CFG.final_flood_points == (6, 3) and CFG.delta_multiplier == 2
    assert "3 for the most markers" in TEXT and "6 for first, 3 for second" in TEXT
    assert CFG.genuine_heir_end_renown == 4 and CFG.impostor_penalty == 2 and CFG.seal_renown == 2
    assert HOUSE_PROFILES["Caddoc"].rite_renown == 2 and HOUSE_PROFILES["Thorne"].succession_bonus == 3


def test_limits_and_thresholds():
    assert CFG.investigation_hand_limit == 3 and CFG.pressure_threshold == 4 and CFG.legion_cap_per_plot == 3
    assert "You can hold three" in TEXT and "Pressure is 4 or more" in TEXT and "up to three per Plot" in TEXT
    assert HOUSE_PROFILES["Sable"].cabal == 2 and CFG.cabal_max == 2 and CFG.cabal_cost_coin == 1


def test_house_modifiers_stated_in_the_doc():
    assert HOUSE_PROFILES["Ash"].skirmish_bonus == 1 and HOUSE_PROFILES["Raven"].skirmish_bonus == -1
    assert "Ash adds 1 and Raven subtracts 1" in TEXT
    assert HOUSE_PROFILES["Thorne"].muster_from == 3 and "Thorne: not before Season 3" in TEXT


def test_links_in_the_doc_point_at_real_files():
    import re
    root = pathlib.Path(__file__).resolve().parent.parent / "docs"
    for target in re.findall(r"\]\(([^)#]+)(?:#[^)]*)?\)", TEXT):
        if target.startswith("http"):
            continue
        if target.startswith("../printables"):
            continue          # generated by tools/build_printables.py, checked in test_printables
        assert (root / target).exists(), target
