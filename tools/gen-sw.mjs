// Writes sw.js: the offline cache for the installed game. It lists every file the game loads,
// with a version hashed from their contents, so a changed file replaces the old cache.
// Run after changing any shipped file: node tools/gen-sw.mjs
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const roots = ['index.html', 'manifest.webmanifest', 'src', 'styles', 'assets', 'vendor/three/three.module.js', 'vendor/three/addons'];
const files = [];
const walk = (p) => { const st = fs.statSync(p); if (st.isDirectory()) for (const f of fs.readdirSync(p).sort()) walk(path.join(p, f)); else if (!/\.(md|txt)$|LICENSE|OFL/.test(p)) files.push(p.split(path.sep).join('/')); };
for (const r of roots) walk(r);
const hash = crypto.createHash('sha256'); for (const f of files) hash.update(f).update(fs.readFileSync(f));
const version = hash.digest('hex').slice(0, 12);
const src = `// Generated by tools/gen-sw.mjs. Do not edit by hand.
// Offline cache for Hollowmere: the whole game is stored on first visit, so it plays without a signal.
const VERSION = 'hollowmere-${version}';
const FILES = ${JSON.stringify(['./', ...files], null, 0).replace(/","/g, '",\n  "')};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('hollowmere-') && k !== VERSION).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
// Cache first (the files are versioned together); anything new, such as web fonts, is cached as it is fetched.
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  e.respondWith(caches.match(req, { ignoreSearch: url.origin === location.origin }).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok && (url.origin === location.origin || /fonts\\.(googleapis|gstatic)\\.com|cdn\\.jsdelivr\\.net/.test(url.host))) { const copy = res.clone(); caches.open(VERSION).then((c) => c.put(req, copy)); }
    return res;
  }).catch(() => (req.mode === 'navigate' ? caches.match('./') : Response.error()))));
});
`;
if (process.argv.includes('--check')) {
  const ok = fs.existsSync('sw.js') && fs.readFileSync('sw.js', 'utf8') === src;
  console.log(ok ? 'sw.js is up to date' : 'sw.js is stale: run node tools/gen-sw.mjs');
  process.exit(ok ? 0 : 1);
}
fs.writeFileSync('sw.js', src);
console.log(JSON.stringify({ version, files: files.length }));
